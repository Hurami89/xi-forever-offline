local T = dofile('/home/claude/cb/tests/helpers.lua')
local games = require('cb.games')
local R = require('cb.rewards')
local util = require('cb.util')

local h = games.header(T.rom('SEIKEN DENSETSU', 0x06))
T.eq(h.title, 'SEIKEN DENSETSU', 'title'); T.eq(h.cart, 'MBC2+battery', 'cart'); T.ok(h.battery, 'battery')
T.ok(h.header_ok, 'header checksum ok'); T.eq(h.checksum, 0x1234, 'global checksum'); T.ok(not h.color, 'not color')
local c = games.header(T.rom('DRAGONWARRIORMON', 0x1B, 0x80))
T.eq(c.title, 'DRAGONWARRIORMO', 'CGB title stops before flag byte'); T.ok(c.color and not c.color_only, 'color flag')
T.eq(c.cart, 'MBC5+RAM+battery', 'mbc5')
local bad = T.rom('X', 0); bad = bad:sub(1, 0x14D) .. '\0' .. bad:sub(0x14F)
T.ok(not games.header(bad).header_ok, 'bad header checksum noticed')
T.ok(games.header('short') == nil, 'short file')
T.eq(select(2, games.header(string.rep('\0', 0x200))), 'no Game Boy header', 'no logo')

local b = string.char(0x00, 0x5A, 0x34, 0x12, 0xFF, 0x00, 0x00, 0x01)
T.ok(R.check_cond(b, { at = 1, equals = 0x5A }), 'equals')
T.ok(not R.check_cond(b, { at = 1, equals = 0x5B }), 'equals false')
T.ok(R.check_cond(b, { at = 2, size = 2, equals = 0x1234 }), '2-byte little endian')
T.ok(R.check_cond(b, { at = 4, size = 4, equals = 0x010000FF }), '4-byte')
T.ok(R.check_cond(b, { at = 4, mask = 0x0F, equals = 0x0F }), 'mask (4-bit save)')
T.ok(R.check_cond(b, { at = 1, min = 0x50, max = 0x60 }), 'range')
T.ok(not R.check_cond(b, { at = 1, min = 0x60 }), 'min false')
T.ok(R.check_cond(b, { at = 1, bits_set = 0x0A }), 'bits_set'); T.ok(not R.check_cond(b, { at = 1, bits_set = 0x01 }), 'bits_set false')
T.ok(R.check_cond(b, { at = 1, bits_clear = 0x05 }), 'bits_clear'); T.ok(not R.check_cond(b, { at = 1, bits_clear = 0x02 }), 'bits_clear false')
T.ok(R.check_cond(b, { at = 1, nonzero = true }), 'nonzero'); T.ok(not R.check_cond(b, { at = 0, nonzero = true }), 'nonzero false')
T.ok(not R.check_cond(b, { at = 99, equals = 0 }), 'out of range fails')
T.ok(not R.check_cond(b, { at = 1 }), 'condition with no test fails')
T.ok(not R.check_cond(b, { at = 1, size = 3, equals = 0 }), 'bad size fails')
T.ok(not R.check_cond(b, 'junk'), 'junk fails')
local mem = { save = b }
T.ok(R.check_rule({ all = { { at = 1, equals = 0x5A }, { at = 7, equals = 1 } } }, mem), 'all')
T.ok(not R.check_rule({ all = { { at = 1, equals = 0x5A }, { at = 7, equals = 2 } } }, mem), 'all false')
T.ok(R.check_rule({ any = { { at = 1, equals = 0 }, { at = 7, equals = 1 } } }, mem), 'any')
T.ok(not R.check_rule({ all = {} }, mem), 'empty rule never finished')
T.ok(not R.check_rule({ memory = 'ram', all = { { at = 1, equals = 0x5A } } }, mem), 'missing memory area')
local d = R.diff('abc', 'axcd')
T.eq(#d, 2, 'diff count'); T.eq(d[1][1], 1, 'diff offset'); T.eq(d[2][2], -1, 'diff past end')

util.save_table('/tmp/cbt.lua', { a = 1, ['SEIKEN DENSETSU'] = { name = 'x"y', ok = true }, list = { 1, 2 } })
local t = util.load_table('/tmp/cbt.lua')
T.eq(t['SEIKEN DENSETSU'].name, 'x"y', 'table round trip'); T.eq(t.list[2], 2, 'list round trip')
local f = io.open('/tmp/cbt2.lua', 'w'); f:write('return os.exit(3)'); f:close()
T.ok(util.load_table('/tmp/cbt2.lua') == nil, 'rule files cannot reach os')
T.eq(util.clean('Hu/ra:mi'), 'Hu_ra_mi', 'clean'); T.eq(util.clean(''), 'default', 'clean empty')
T.eq(util.band(0xF5, 0x0F), 5, 'band fallback')
T.done('units')
